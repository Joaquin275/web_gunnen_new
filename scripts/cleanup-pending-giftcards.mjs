/**
 * Script de limpieza: elimina o devuelve al pool los bonos PENDING_PAYMENT
 * que quedaron abandonados (pago no completado).
 */

import { PrismaClient } from "@prisma/client";

const prisma = new PrismaClient();

const stale = await prisma.giftCard.findMany({
  where: { status: "PENDING_PAYMENT" },
  select: { id: true, code: true, autoGenerated: true, createdAt: true, purchaserEmail: true },
});

console.log(`\nBonos PENDING_PAYMENT encontrados: ${stale.length}\n`);

let deleted = 0;
let restored = 0;

for (const card of stale) {
  if (card.autoGenerated) {
    await prisma.giftCard.delete({ where: { id: card.id } });
    console.log(`  ❌ Eliminado (auto-generado): ${card.code} — ${card.purchaserEmail} — ${card.createdAt.toLocaleDateString("es-ES")}`);
    deleted++;
  } else {
    await prisma.giftCard.update({
      where: { id: card.id },
      data: {
        status: "AVAILABLE",
        purchaserName: "INVENTARIO",
        purchaserEmail: "inventario@gunnen.local",
        recipientName: null,
        recipientEmail: "inventario@gunnen.local",
        message: null,
        menuName: null,
        stripePaymentIntentId: null,
        paidAt: null,
      },
    });
    console.log(`  ♻️  Restaurado (inventario): ${card.code} — ${card.purchaserEmail} — ${card.createdAt.toLocaleDateString("es-ES")}`);
    restored++;
  }
}

console.log(`\nResumen: ${deleted} eliminados, ${restored} restaurados al inventario.\n`);

await prisma.$disconnect();
